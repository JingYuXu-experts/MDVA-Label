import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {mkdir,writeFile} from 'node:fs/promises'
const out='../out/acceptance/diagnostics-20261115';await mkdir(out,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true})
const errors=[]
try{
 const p=await browser.newPage({viewport:{width:1600,height:1050}});p.on('pageerror',e=>errors.push(e.message))
 await p.goto('http://127.0.0.1:8765/training')
 const panel=p.getByRole('region',{name:'识别效果诊断'})
 await panel.locator('.case-grid button').first().waitFor({timeout:30000})
 await panel.scrollIntoViewIfNeeded();await p.screenshot({path:out+'/desktop-report.png'})
 await panel.locator('.case-grid button').first().click()
 await panel.locator('.case-detail').scrollIntoViewIfNeeded()
 await panel.getByAltText('右模型同图',{exact:true}).waitFor()
 await p.waitForFunction(()=>[...document.querySelectorAll('.case-detail img')].every(i=>i.complete&&i.naturalWidth>0))
 await panel.locator('.image-comparison figure').nth(2).scrollIntoViewIfNeeded()
 await p.screenshot({path:out+'/same-image-comparison.png'})
 await p.getByLabel('参考标注透明度',{exact:true}).fill('0.7')
 assert.equal(await panel.locator('.image-stack').first().locator('img').nth(1).evaluate(e=>e.style.opacity),'0.7')
 await p.getByLabel('诊断台站',{exact:true}).selectOption('KSO_Halpha')
 await p.waitForFunction(()=>[...document.querySelectorAll('.case-grid span')].every(e=>e.textContent.includes('KSO_Halpha')))
 await p.getByLabel('诊断案例排序',{exact:true}).selectOption('worst')
 await p.waitForTimeout(500)
 await p.getByLabel('诊断台站',{exact:true}).selectOption('')
 await p.getByLabel('诊断任务',{exact:true}).selectOption('AR')
 await p.waitForFunction(()=>document.querySelector('.case-detail .uri')?.textContent.includes('@ssafd/AR/'))
 await p.getByLabel('诊断任务',{exact:true}).selectOption('FL')
 await p.waitForFunction(()=>document.querySelector('.case-detail .uri')?.textContent.includes('@ssafd/FL/'))
 await p.getByLabel('诊断案例排序',{exact:true}).selectOption('fixed')
 await p.waitForTimeout(500)
 await panel.locator('.case-grid button').first().click()
 const downloadWait=p.waitForEvent('download')
 await panel.getByRole('link',{name:'下载诊断结论与后续取舍',exact:true}).click()
 const download=await downloadWait
 await download.saveAs(out+'/downloaded-interpretation.md')
 await p.setViewportSize({width:390,height:844})
 await p.waitForFunction(()=>[...document.querySelectorAll('.case-detail img')].every(i=>i.complete&&i.naturalWidth>0))
 await panel.locator('.image-comparison figure').nth(2).scrollIntoViewIfNeeded()
 await p.screenshot({path:out+'/mobile-comparison.png'})
 assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const paused=await (await p.request.get('http://127.0.0.1:8765/api/training/summary')).json()
 assert.equal(paused.progress.paused_requested,true);assert.equal(paused.progress.automatic_continuation,false)
 assert.deepEqual(errors,[])
 await writeFile(out+'/browser.json',JSON.stringify({actual_sources:true,independent_training_pause:true,model_overlay_same_image:true,station_filter:true,category_switch:true,opacity_control:true,mobile_no_overflow:true,report_download:true,errors},null,2))
 console.log('Actual diagnostic report, same-image overlays, filters, opacity and mobile passed')
}finally{await browser.close()}
