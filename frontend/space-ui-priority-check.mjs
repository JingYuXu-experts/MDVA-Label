import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {mkdir,writeFile} from 'node:fs/promises'
const origin=process.env.MDVA_MONITOR_TEST_ORIGIN||'http://127.0.0.1:8765'
const output='../out/acceptance/space-ui-priority-20261112'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl']})
const errors=[]
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080}})
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto(origin+'/monitor')
 const scene=page.locator('.solar-studio'),summary=page.locator('.impact-brief')
 await page.locator('.solar-studio[data-render-state=ready]').waitFor({timeout:30000})
 assert.equal(await page.locator('.scene-guide').count(),0)
 assert.equal(await page.locator('.scene-caption,.guide-source-note,.scene-tools').count(),0)
 assert.equal(await page.locator('.event-library[open],.event-verification[open],.impact-details details[open]').count(),0)
 assert.ok(await summary.getByRole('link',{name:'NOAA 影响等级与适用范围 ↗',exact:true}).isVisible())
 const first=await summary.boundingBox(),stage=await page.locator('.scene-stage').boundingBox()
 assert.ok(first.y+first.height<=stage.y+1)
 // Main library and scientific evidence remain available without taking over the initial screen.
 await page.locator('.event-library>summary').click()
 const events=page.locator('.event-list button')
 await events.first().waitFor({timeout:15000})
 await events.first().click()
 const eventId=await page.getByLabel('影响摘要的喷发事件',{exact:true}).inputValue()
 assert.ok(eventId)
 await page.locator('.event-verification>summary').click()
 assert.ok((await page.locator('.event-verification').innerText()).includes(eventId))
 await page.locator('.event-verification>summary').click()
 await page.locator('.event-library>summary').click()
 await page.getByRole('button',{name:'进入三维全屏',exact:false}).click()
 await page.mouse.move(1900,20)
 await page.waitForTimeout(1500)
 const top=await summary.boundingBox(),canvas=await page.locator('.scene-stage').boundingBox()
 assert.ok(top.y+top.height<=canvas.y+1)
 assert.ok(top.y+top.height<350)
 assert.ok(await page.locator('.impact-arrival strong').isVisible())
 await page.screenshot({path:output+'/desktop-selected-event.png'})
 // Collapse and restore use independent visibility controls, without clearing selection.
 await page.getByRole('button',{name:'收起摘要',exact:true}).click()
 assert.equal(await summary.count(),0)
 await page.getByRole('button',{name:'显示影响摘要',exact:true}).click()
 assert.equal(await page.getByLabel('影响摘要的喷发事件',{exact:true}).inputValue(),eventId)
 await page.locator('.display-settings>summary').click()
 await page.getByLabel('观测时间与来源',{exact:true}).check()
 assert.ok(await page.locator('.guide-source-note').isVisible())
 await page.getByLabel('观测时间与来源',{exact:true}).uncheck()
 await page.getByLabel('四步图解说明',{exact:true}).check()
 assert.ok(await page.locator('.scene-guide').isVisible())
 await page.locator('.display-settings>summary').click()
 await page.getByRole('button',{name:'收起图解',exact:true}).click()
 assert.equal(await page.locator('.scene-guide').count(),0)
 await page.getByRole('button',{name:'专业浏览',exact:true}).click()
 await page.locator('.scene-tools').waitFor()
 await page.locator('.display-settings>summary').click()
 await page.getByLabel('专业控制面板',{exact:true}).uncheck()
 assert.equal(await page.locator('.scene-tools').count(),0)
 await page.locator('.display-settings>summary').click()
 await page.getByRole('button',{name:'简洁浏览',exact:true}).click()
 await page.setViewportSize({width:390,height:844})
 await page.mouse.move(389,0)
 await page.waitForTimeout(1000)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const mobile=await summary.boundingBox()
 assert.ok(mobile.x>=0&&mobile.x+mobile.width<=391)
 assert.ok(mobile.y+mobile.height<400,'Primary summary must remain above the fold on mobile')
 assert.ok(await page.locator('.impact-arrival strong').isVisible())
 await page.screenshot({path:output+'/mobile-selected-event.png'})
 await page.getByRole('button',{name:'太阳活动观测',exact:true}).click()
 assert.equal(await summary.count(),0)
 await page.getByRole('button',{name:'太阳风怎样到地球',exact:true}).click()
 assert.ok(await summary.isVisible())
 assert.equal(await page.getByLabel('影响摘要的喷发事件',{exact:true}).inputValue(),eventId)
 assert.deepEqual(errors,[])
 const training=await (await page.request.get(origin+'/api/training/summary')).json()
 await writeFile(output+'/acceptance.json',JSON.stringify({actual_sources:true,software_webgl:true,selected_event:eventId,default_details_collapsed:true,top_summary:true,noaa_link_visible:true,controls_restore_selection:true,mobile_summary_height:mobile.height,training:training.progress.active,errors},null,2))
 console.log('Top impact summary, collapsible details, display controls and mobile layout passed')
}finally{await browser.close()}
