import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import {fileURLToPath} from 'node:url'
const output=fileURLToPath(new URL('../out/acceptance',import.meta.url))
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||'C:/Users/Administrator/AppData/Local/ms-playwright/chromium-1217/chrome-win64/chrome.exe'})
const context=await browser.newContext({viewport:{width:1920,height:1080},recordVideo:{dir:output+'/space-science-video',size:{width:1920,height:1080}}})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
try{
 await page.goto('http://127.0.0.1:8765/monitor')
 await page.locator('.solar-studio[data-render-state=ready]').waitFor({timeout:30000})
 await page.getByRole('button',{name:'专业浏览',exact:true}).click()
 await page.getByRole('button',{name:'进入三维全屏',exact:false}).click()
 await page.getByLabel('天体时间倍率').selectOption('3600')
 const scene=page.locator('.solar-studio')
 const t0=Number(await scene.getAttribute('data-scene-time'))
 await page.waitForTimeout(550)
 assert.ok(Number(await scene.getAttribute('data-scene-time'))>t0+500,'Physical clock did not advance')
 await page.getByRole('button',{name:'暂停天体运动',exact:true}).click()
 const frozen=Number(await scene.getAttribute('data-scene-time'))
 await page.waitForTimeout(1250)
 assert.equal(Number(await scene.getAttribute('data-scene-time')),frozen)
 await page.getByRole('button',{name:'继续天体运动',exact:true}).click()
 await page.getByRole('button',{name:'全局磁层',exact:true}).click()
 await page.waitForTimeout(1300)
 await page.locator('[data-lesson=field]').hover()
 await page.getByRole('tooltip').waitFor()
 assert.match(await page.getByRole('tooltip').innerText(),/不是磁场终止/)
 await page.screenshot({path:output+'/science-field-lesson-20261111.png'})
 await page.locator('[data-lesson=field]').click()
 await page.getByRole('dialog').waitFor()
 await page.getByRole('button',{name:'关闭讲解',exact:true}).click()
 // Inspect the rendered object itself, not only a text button.
 await page.getByRole('button',{name:'地球近景',exact:true}).click()
 await page.waitForTimeout(1300)
 await page.mouse.move(960,530)
 await page.getByRole('tooltip').waitFor()
 assert.match(await page.getByRole('tooltip').innerText(),/地球|磁场/)
 await page.locator('[data-lesson=shock]').click()
 assert.match(await page.getByRole('dialog').innerText(),/没有生成冲击波网格/)
 await page.getByRole('button',{name:'关闭讲解',exact:true}).click()
 await page.locator('[data-lesson=wind]').click()
 assert.match(await page.getByRole('dialog').innerText(),/L1|缺测|监测时间/)
 await page.getByRole('button',{name:'关闭讲解',exact:true}).click()
 await page.getByRole('button',{name:'返回当前时间',exact:true}).click()
 assert.ok(Math.abs(Number(await scene.getAttribute('data-scene-time'))-Date.now()/1000)<5)
 await page.screenshot({path:output+'/science-earth-20261111.png'})
 await page.getByRole('button',{name:'退出全屏',exact:false}).click()
 await page.getByRole('button',{name:'官方二维模型',exact:true}).click()
 await page.locator('.model-image img').waitFor()
 assert.equal(await page.locator('.space-viewport canvas').count(),0)
 await page.getByRole('button',{name:'三维日地场景',exact:true}).click()
 await page.locator('.solar-studio[data-render-state=ready]').waitFor()
 await page.setViewportSize({width:390,height:844})
 await page.getByRole('button',{name:'专业浏览',exact:true}).click()
 await page.locator('[data-lesson=earth]').click()
 await page.getByRole('dialog').waitFor()
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.screenshot({path:output+'/science-mobile-lesson-20261111.png',fullPage:true})
 assert.deepEqual(errors,[])
 fs.writeFileSync(output+'/science-browser-20261111.json',JSON.stringify({physical_clock:true,pause:true,return_to_now:true,field_reference:true,hover_object:true,hover_lessons:true,tap_lessons:true,unsupported_shock_disclosed:true,unsupported_global_flow_disclosed:true,official_2d_preserved:true,canvas_disposed:true,mobile_overflow:false,errors},null,2))
 console.log('Science and education browser checks passed')
}finally{await context.close();await browser.close()}
