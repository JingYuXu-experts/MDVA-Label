import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {mkdir,writeFile} from 'node:fs/promises'
const origin=process.env.MDVA_GUIDE_TEST_ORIGIN||'http://127.0.0.1:5173'
const output='../out/acceptance/space-guide-20261112'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl']})
try{
 const page=await browser.newPage({viewport:{width:1920,height:1080}}),errors=[]
 let modelRequests=0
 page.on('pageerror',e=>errors.push(e.message))
 page.on('request',r=>{if(r.method()==='POST'&&r.url().includes('/sw/magnetosphere/model'))modelRequests++})
 await page.goto(origin+'/monitor')
 const scene=page.locator('.solar-studio')
 await page.locator('.solar-studio[data-render-state=ready]').waitFor({timeout:30000})
 assert.equal(await scene.getAttribute('data-experience'),'guided')
 assert.equal(await scene.getAttribute('data-guide-step'),'1')
 await page.waitForFunction(()=>Number(document.querySelector('.solar-studio')?.dataset.windTracers)>0)
 assert.equal(await page.locator('.scene-tools').count(),0)
 assert.equal(await page.locator('.impact-brief').count(),1)
 assert.equal(await page.locator('.scene-guide').count(),0)
 await page.getByRole('button',{name:'图解说明',exact:true}).click()
 await page.getByRole('button',{name:/1.*认位置/}).click()
 assert.equal(modelRequests,0,'Default location lesson starts an unnecessary field computation')
 await page.getByRole('button',{name:'进入三维全屏',exact:false}).click()
 await page.getByRole('button',{name:'了解太阳',exact:true}).waitFor()
 await page.getByRole('button',{name:'了解地球',exact:true}).waitFor()
 await page.locator('.solar-studio[data-solar-observed=true]').waitFor({timeout:65000})
 await page.screenshot({path:output+'/actual-1-position.png'})
 await page.getByRole('button',{name:'下一步：看太阳风',exact:true}).click()
 await page.waitForFunction(()=>Number(document.querySelector('.solar-studio')?.dataset.windTracers)>0)
 assert.equal(await scene.getAttribute('data-guide-step'),'1')
 assert.match(await page.locator('.scene-guide').innerText(),/它一直存在|看到太阳风并不等于/)
 await page.screenshot({path:output+'/actual-2-wind.png'})
 await page.getByRole('button',{name:'下一步：看地球磁场',exact:true}).click()
 assert.equal(await scene.getAttribute('data-field-visible'),'true')
 await page.waitForFunction(()=>{const text=document.querySelector('.guide-state')?.textContent||'';return /快照|全局模型未取得/.test(text)},null,{timeout:90000})
 const fieldState=await page.locator('.guide-state').innerText()
 await page.waitForTimeout(1000)
 await page.screenshot({path:output+'/actual-3-field.png'})
 assert.ok(modelRequests>=1)
 await page.getByRole('button',{name:'下一步：查具体喷发',exact:true}).click()
 await page.locator('.impact-brief').waitFor()
 const options=page.getByLabel('讲解中的喷发事件',{exact:true}).locator('option')
 if(await options.count()>1){await page.getByLabel('讲解中的喷发事件',{exact:true}).selectOption(await options.nth(1).getAttribute('value'));await page.waitForTimeout(500)}
 assert.match(await page.locator('.scene-guide').innerText(),/当前没有重建CME三维冲击过程/)
 await page.screenshot({path:output+'/actual-4-event.png'})
 await page.getByRole('button',{name:'专业浏览',exact:true}).click()
 await page.locator('.scene-tools').waitFor()
 assert.equal(await page.locator('.scene-guide').count(),0)
 assert.ok(await page.getByLabel('三维CME事件',{exact:true}).isVisible())
 await page.getByRole('button',{name:'简洁浏览',exact:true}).click()
 await page.getByRole('button',{name:/1.*认位置/}).click()
 await page.getByRole('button',{name:'收起摘要',exact:true}).click()
 assert.equal(await scene.getAttribute('data-guide-step'),'0')
 assert.equal(await page.locator('.impact-brief').count(),0)
 await page.setViewportSize({width:390,height:844})
 await page.waitForFunction(()=>{
  const labels=[...document.querySelectorAll('.body-label')]
  return labels.length===2&&labels.every(label=>{const box=label.getBoundingClientRect();return box.x>=0&&box.x+box.width<=innerWidth&&box.y>=0&&box.y+box.height<innerHeight*.67})
 })
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 const bounds=await page.locator('.scene-guide').boundingBox()
 assert.ok(bounds.x>=0&&bounds.x+bounds.width<=391)
 await page.screenshot({path:output+'/actual-mobile-position.png'})
 await page.getByRole('button',{name:'太阳活动观测',exact:true}).click()
 assert.equal(await page.locator('.scene-guide').isVisible(),false)
 await page.getByRole('button',{name:'太阳风怎样到地球',exact:true}).click()
 assert.equal(await page.locator('.scene-guide').isVisible(),true)
 assert.deepEqual(errors,[])
 const failure=await browser.newPage()
 let retries=0
 failure.on('pageerror',e=>errors.push(e.message))
 await failure.route('**/api/sw/magnetosphere/model*',route=>{retries++;return route.fulfill({status:503,json:{error:'隔离验收：缺少Dst'}})})
 await failure.goto(origin+'/monitor')
 await failure.getByRole('button',{name:'图解说明',exact:true}).click()
 await failure.getByRole('button',{name:'下一步：看地球磁场',exact:true}).click()
 await failure.getByRole('button',{name:'重试全局磁场',exact:true}).waitFor()
 assert.match(await failure.locator('.guide-state').innerText(),/全局模型未取得/)
 await failure.getByRole('button',{name:'重试全局磁场',exact:true}).click()
 await failure.waitForFunction(()=>document.querySelector('.guide-state')?.textContent.includes('全局模型未取得'))
 assert.equal(retries,2)
 assert.deepEqual(errors,[])
 await writeFile(output+'/actual-browser.json',JSON.stringify({actual_sources:true,software_webgl:true,optional_position_lesson:true,lazy_magnetic_model:true,field_state:fieldState,four_guided_steps:true,expert_controls_preserved:true,mobile_both_bodies_visible:true,mobile_no_overflow:true,errors},null,2))
 console.log('Four-step guide, actual field state, expert controls and mobile view passed')
}finally{await browser.close()}
